// Command gen_vendor_defaults expands the semver-constraint keys of the vendor
// defaults source file into one entry per installable Istio version, producing
// pkg/istiovalues/vendor_defaults.yaml.
//
// The runtime looks up vendor defaults by exact version string, so every
// supported version needs its own entry. Maintaining that list by hand goes
// stale on every patch release; this generator derives it from versions.yaml
// instead.
package main

import (
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/Masterminds/semver/v3"
	"gopkg.in/yaml.v3"
)

const (
	defaultSrcPath      = "ossm/vendor_defaults.src.yaml"
	defaultOutPath      = "pkg/istiovalues/vendor_defaults.yaml"
	defaultVersionsPath = "pkg/istioversion/versions.ossm.yaml"

	// header is deliberately free of file paths so that the output depends only
	// on the source file and the version list, never on how the tool was invoked.
	header = `# Code generated by hack/gen_vendor_defaults. DO NOT EDIT.
#
# Generated from ` + defaultSrcPath + `, expanded over the installable versions
# listed in pkg/istioversion. To change these defaults, edit the source file and
# run 'make gen-vendor-defaults' (or 'make gen').
`
)

// resourceTypes are the keys the runtime recognizes below a version entry; see
// applyVendorDefaultsForResourceType in pkg/istiovalues/vendor_defaults.go.
var resourceTypes = []string{"istio", "istiocni", "ztunnel"}

type versionsFile struct {
	Versions []struct {
		Name string `yaml:"name"`
		Ref  string `yaml:"ref"`
		EOL  bool   `yaml:"eol"`
	} `yaml:"versions"`
}

// rule is one entry of the source file: a semver constraint and the defaults to
// apply to every version satisfying it.
type rule struct {
	key        string
	constraint *semver.Constraints
	values     map[string]any
}

func main() {
	versionsPath := flag.String("versions", defaultVersionsPath, "path to the versions YAML file")
	srcPath := flag.String("src", defaultSrcPath, "path to the vendor defaults source file")
	outPath := flag.String("out", defaultOutPath, "path to the generated file")
	flag.Parse()

	versions, err := readVersions(*versionsPath)
	if err != nil {
		fatal(err)
	}
	rules, err := readRules(*srcPath)
	if err != nil {
		fatal(err)
	}

	out, entries, err := expand(rules, versions)
	if err != nil {
		fatal(err)
	}
	for _, key := range unmatchedRules(rules, versions) {
		// Either a stale pin for a version this branch no longer ships, or a
		// version-bounded workaround that has aged out. The second is a
		// legitimate end state, so this warns rather than fails.
		fmt.Fprintf(os.Stderr, "gen_vendor_defaults: warning: rule %q matches none of "+
			"the installable versions in %s\n", key, *versionsPath)
	}
	if err := os.WriteFile(*outPath, []byte(out), 0o644); err != nil {
		fatal(err)
	}
	fmt.Fprintf(os.Stderr, "gen_vendor_defaults: wrote %s (%d rule(s) -> %d version entries)\n",
		*outPath, len(rules), entries)
}

// readVersions returns the installable versions in file order, skipping aliases
// (which resolve to a concrete version before the runtime lookup happens) and
// end-of-life entries (which cannot be installed). This is the same filter the
// download-istio-charts target applies in Makefile.core.mk.
func readVersions(path string) ([]*semver.Version, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading versions file: %w", err)
	}
	var vf versionsFile
	if err := yaml.Unmarshal(data, &vf); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}

	var out []*semver.Version
	for _, v := range vf.Versions {
		if v.Ref != "" || v.EOL {
			continue
		}
		parsed, err := semver.NewVersion(v.Name)
		if err != nil {
			return nil, fmt.Errorf("version %q in %s is not valid semver: %w", v.Name, path, err)
		}
		out = append(out, parsed)
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no installable versions found in %s", path)
	}
	return out, nil
}

// readRules parses the source file, preserving document order so that
// precedence between overlapping constraints is "later entry wins".
func readRules(path string) ([]rule, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading source file: %w", err)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	if len(doc.Content) == 0 {
		return nil, nil // a source file with no rules is valid; it generates an empty output
	}
	root := doc.Content[0]
	if root.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("%s: expected a mapping at the top level", path)
	}

	var rules []rule
	var problems []string
	for i := 0; i+1 < len(root.Content); i += 2 {
		keyNode, valNode := root.Content[i], root.Content[i+1]

		constraint, err := semver.NewConstraint(keyNode.Value)
		if err != nil {
			problems = append(problems, fmt.Sprintf("line %d: key %q is not a valid semver constraint: %v",
				keyNode.Line, keyNode.Value, err))
			continue
		}

		var values map[string]any
		if err := valNode.Decode(&values); err != nil {
			problems = append(problems, fmt.Sprintf("line %d: key %q: %v", keyNode.Line, keyNode.Value, err))
			continue
		}
		// Guard against omitting the resource-type level, which the runtime
		// silently ignores rather than reporting.
		for name := range values {
			if !slices.Contains(resourceTypes, name) {
				problems = append(problems, fmt.Sprintf("line %d: key %q: %q is not a resource type; expected one of %s",
					keyNode.Line, keyNode.Value, name, strings.Join(resourceTypes, ", ")))
			}
		}
		rules = append(rules, rule{key: keyNode.Value, constraint: constraint, values: values})
	}
	if len(problems) > 0 {
		return nil, fmt.Errorf("%s:\n  %s", path, strings.Join(problems, "\n  "))
	}
	return rules, nil
}

// expand renders the generated file and reports how many version entries it holds.
func expand(rules []rule, versions []*semver.Version) (string, int, error) {
	var b strings.Builder
	b.WriteString(header)

	entries := 0
	for _, v := range versions {
		merged := map[string]any{}
		for _, r := range rules {
			if r.constraint.Check(v) {
				mergeInto(merged, r.values) // later rules win
			}
		}
		if len(merged) == 0 {
			continue
		}
		body, err := marshalIndent2(merged)
		if err != nil {
			return "", 0, err
		}
		fmt.Fprintf(&b, "v%s:\n%s", v.String(), indent(body, "  "))
		entries++
	}
	return b.String(), entries, nil
}

// unmatchedRules returns the keys of rules that no installable version satisfies.
func unmatchedRules(rules []rule, versions []*semver.Version) []string {
	var out []string
	for _, r := range rules {
		if !slices.ContainsFunc(versions, r.constraint.Check) {
			out = append(out, r.key)
		}
	}
	return out
}

// mergeInto deep-merges src into dst, with src taking precedence.
func mergeInto(dst, src map[string]any) {
	for k, sv := range src {
		if sm, ok := sv.(map[string]any); ok {
			if dm, ok := dst[k].(map[string]any); ok {
				mergeInto(dm, sm)
				continue
			}
		}
		dst[k] = sv
	}
}

// marshalIndent2 marshals with 2-space indentation, matching the repo's YAML style.
func marshalIndent2(v any) (string, error) {
	var buf strings.Builder
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return "", err
	}
	if err := enc.Close(); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func indent(s, prefix string) string {
	var b strings.Builder
	for line := range strings.SplitSeq(strings.TrimRight(s, "\n"), "\n") {
		b.WriteString(prefix)
		b.WriteString(line)
		b.WriteByte('\n')
	}
	return b.String()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen_vendor_defaults: "+err.Error())
	os.Exit(1)
}
